"""Analytics job contract: JSON Schema exported from Zod plus its refinements.

The schema file is generated by `pnpm gen:analytics-schema`; the semantic checks below
mirror the Zod `.refine` calls in packages/contracts/src/analytics-jobs.ts and share
the cases in packages/contracts/test/fixtures/analytics-job-cases.json.
"""

import json
import math
import re
from collections.abc import Iterator, Mapping
from dataclasses import dataclass
from decimal import Decimal
from importlib.resources import files
from typing import Any, NamedTuple, cast
from uuid import UUID

from jsonschema import Draft202012Validator  # type: ignore[import-untyped]
from jsonschema.exceptions import ValidationError  # type: ignore[import-untyped]
from jsonschema.validators import extend  # type: ignore[import-untyped]

_DOCUMENT: dict[str, Any] = json.loads(
    files("oliginvest_analytics")
    .joinpath("schemas/analytics-jobs.schema.json")
    .read_text(encoding="utf-8")
)
VERSION: int = _DOCUMENT["version"]
JOB_TYPES: tuple[str, ...] = tuple(_DOCUMENT["jobTypes"])
LIMITS: dict[str, int] = _DOCUMENT["limits"]
TIMEOUTS_SECONDS: dict[str, int] = _DOCUMENT["timeoutsSeconds"]
_MAX_DEPTH = 16
_MAX_STRING = 256
_UUID = re.compile(r"[0-9a-fA-F]{8}(?:-[0-9a-fA-F]{4}){3}-[0-9a-fA-F]{12}")


def _ascii_pattern(
    validator: Any, pattern: str, instance: object, schema: object
) -> Iterator[ValidationError]:
    # ECMA-262 `\d` is ASCII-only; Python's is not without re.ASCII.
    if isinstance(instance, str) and not re.search(pattern, instance, re.ASCII):
        yield ValidationError("does not match pattern")


_Validator = extend(Draft202012Validator, {"pattern": _ascii_pattern})
for _schema in (_DOCUMENT["job"], _DOCUMENT["result"]):
    Draft202012Validator.check_schema(_schema)
_JOB = _Validator(_DOCUMENT["job"], format_checker=Draft202012Validator.FORMAT_CHECKER)
_RESULT = _Validator(
    _DOCUMENT["result"], format_checker=Draft202012Validator.FORMAT_CHECKER
)


class InvalidJob(ValueError):
    """Rejected before any processing; carries only the run id, never the payload."""

    def __init__(self, run_id: UUID | None) -> None:
        super().__init__("Invalid analytics job")
        self.run_id = run_id


@dataclass(frozen=True)
class ValidatedJob:
    run_id: UUID
    type: str
    data: Mapping[str, Any]


class Money(NamedTuple):
    amount: Decimal
    currency: str


def read_money(value: Mapping[str, Any]) -> Money:
    """Decimal at the boundary (ADR-014); the schema already fixed the text format."""
    return Money(Decimal(cast(str, value["amount"])), cast(str, value["currency"]))


def _run_id(data: object) -> UUID | None:
    candidate = data.get("runId") if isinstance(data, dict) else None
    if isinstance(candidate, str) and _UUID.fullmatch(candidate):
        return UUID(candidate)
    return None


def _structure_ok(value: object, depth: int = 0) -> bool:
    """JSON-only shapes: Python's json accepts NaN/Infinity, which bounds cannot catch."""
    if depth > _MAX_DEPTH:
        return False
    if isinstance(value, dict):
        return all(
            isinstance(key, str) and _structure_ok(key, depth + 1) for key in value
        ) and all(_structure_ok(item, depth + 1) for item in value.values())
    if isinstance(value, list):
        return all(_structure_ok(item, depth + 1) for item in value)
    if isinstance(value, str):
        return len(value) <= _MAX_STRING and not any(
            ord(char) < 32 or ord(char) == 127 for char in value
        )
    if isinstance(value, float):
        return math.isfinite(value)
    return value is None or isinstance(value, (bool, int))


def _unique(values: list[Any]) -> bool:
    return len(set(values)) == len(values)


def _ordered(range_: Mapping[str, str]) -> bool:
    # ISO dates (pattern-checked) order lexicographically.
    return range_["from"] < range_["to"]


def _portfolio_ok(job: Mapping[str, Any]) -> bool:
    positions = job["portfolio"]["positions"]
    return _unique([item["instrumentId"] for item in positions])


def _rule_group_ok(group: Mapping[str, list[object]]) -> bool:
    return len(group.get("all", [])) + len(group.get("any", [])) > 0


def _semantics_ok(job: Mapping[str, Any]) -> bool:
    """Refinements that JSON Schema cannot express (Zod `.refine` twins)."""
    params = job["params"]
    kind = job["type"]
    if kind == "monte_carlo":
        flows = params["contributions"] + params["withdrawals"]
        return _portfolio_ok(job) and all(
            flow["startYear"] <= flow["endYear"] <= params["horizonYears"]
            for flow in flows
        )
    if kind == "optimization":
        return (
            _unique(params["instrumentIds"])
            and _ordered(params["window"])
            and params["minWeight"] <= params["maxWeight"]
        )
    if kind == "stress_test":
        return (
            _portfolio_ok(job)
            and all(_ordered(item) for item in params["historical"])
            and len(params["historical"]) + len(params["hypothetical"]) > 0
        )
    if kind == "what_if":
        return _portfolio_ok(job)
    if kind == "backtest":
        strategy, universe = params["strategy"], params["universe"]
        grid = params["optimization"].get("grid", {})
        combinations = math.prod(len(values) for values in grid.values())
        return (
            _rule_group_ok(strategy["entry"])
            and _rule_group_ok(strategy["exit"])
            and _unique(universe.get("instrumentIds", []))
            and _ordered(params["period"])
            and (
                not params["optimization"]["enabled"]
                or 1 <= len(grid) <= LIMITS["backtestGridParameters"]
            )
            and combinations <= LIMITS["backtestCombinations"]
        )
    if kind == "goal":
        return _portfolio_ok(job) and _unique(params["probabilities"])
    return False


def validate_job(name: str, data: object) -> ValidatedJob:
    """Check size, shape, schema and limits before anything else touches the job."""
    run_id = _run_id(data)
    if not _structure_ok(data):
        raise InvalidJob(run_id)
    if len(json.dumps(data, separators=(",", ":"))) > LIMITS["jobPayloadBytes"]:
        raise InvalidJob(run_id)
    if not _JOB.is_valid(data):
        raise InvalidJob(run_id)
    job = cast(dict[str, Any], data)
    if name != job["type"] or not _semantics_ok(job):
        raise InvalidJob(run_id)
    return ValidatedJob(UUID(job["runId"]), job["type"], job)


def check_result(result: Mapping[str, Any]) -> bool:
    return bool(_RESULT.is_valid(result))
